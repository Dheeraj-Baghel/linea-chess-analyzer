// Builds homepage demo evidence with the REAL local engine and unchanged review policy.
// Run on demand: npx playwright test --config playwright.product.config.js tests/product/demo-evidence.spec.js
// Output: tests/fixtures/demo/report-evidence.json (manifest + buildPlayerReport output).
import { test, expect } from '../browser/fixtures.js';
import fs from 'node:fs/promises';
import { DEMO_REPORT_GAMES } from '../fixtures/demo/report-games.js';

test('ten-game demo report is produced by the actual batch review', async ({ page }) => {
  test.skip(!process.env.LINEA_BUILD_DEMO, 'Set LINEA_BUILD_DEMO=1 to regenerate demo evidence.');
  test.setTimeout(900000);
  await page.goto('/sample');
  await page.evaluate(async () => { const [{ createLibrary }, { createEngineCoordinator }, { createBatchReview }] = await Promise.all([import('/src/library.js'), import('/src/engineCoordinator.js'), import('/src/batchReview.js')]); window.__batch = createBatchReview({ library: createLibrary(), coordinator: createEngineCoordinator() }); });
  await page.evaluate(games => window.__batch.start({ provider: 'chesscom', username: 'Demo Player', filter: 'all', games }), DEMO_REPORT_GAMES);
  await expect.poll(() => page.evaluate(() => window.__batch.getSnapshot().manifest?.status), { timeout: 880000, intervals: [5000] }).toMatch(/^completed/);
  const snapshot = await page.evaluate(() => structuredClone(window.__batch.getSnapshot()));
  expect(snapshot.report.selected).toBe(10);
  await fs.writeFile('tests/fixtures/demo/report-evidence.json', JSON.stringify({ generatedAt: new Date().toISOString(), note: 'Generated by the real batch review; display identities are fictional.', manifest: snapshot.manifest, report: snapshot.report }));
});
